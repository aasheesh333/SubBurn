def main() -> None:
    tools = []
    for i, (name, vendor, mark, color, category, price, url, popular) in enumerate(TOOLS):
        tools.append(
            {
                "id": f"{name.lower().replace(' ', '_').replace('+', 'plus').replace('.', '')}_{i:03d}",
                "name": name,
                "vendor": vendor,
                "monogram": mark,
                "brandColor": color,
                "category": category,
                "defaultPrice": price,
                "currency": "INR",
                "cycle": "monthly",
                "cancelUrl": url,
                "popular": popular,
            }
        )

    payload = {
        "version": 1,
        "generatedAt": "2026-11-09",
        "currency": "INR",
        "tools": tools,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    RATES.write_text(
        json.dumps(
            {
                "base": "USD",
                "inrPerUsd": 83.0,
                "asOf": "2026-11-09",
                "source": "subburn-static",
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(tools)} tools -> {OUT}")
    print(f"wrote rates -> {RATES}")


